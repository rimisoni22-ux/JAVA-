
import java.util.Scanner;

public class printrectangle {
    //R=3,C=6;
    public static void main(String[] args) {
         Scanner Sc = new Scanner (System.in);
         int R = Sc.nextInt();
         int C = Sc.nextInt();
        for (int i =1; i<=R;i++){
            for (int j =1; j<=C; j++){
                System.out.print("*");
            
        }System.out.println();
    }
        
    }
    
}
