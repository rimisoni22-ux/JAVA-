public class Switch {
    public static void main(String[] args) {
        int number = 4;
        switch (number){
            case 1 :System.out.println("samosa");
            break;
            case 2 :System.out.println("maggie");
            break;
            case 3 :System.out.println("pasta");
            break;
            case 4 :System.out.println("burger");
            break;
            
            default:System.out.println(" we wake up ");
            
        }
        
    }
     

}
