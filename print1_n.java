import java.util.*;
public class print1_n {
    public static void main(String[] args) {
        Scanner Sc =new Scanner (System.in);
        int range =Sc.nextInt();
        int counter =1;
        while (counter<=range){
            System.out.println(counter+"");
            counter++;


        }
        System.out.println();


        
    }
    
}
